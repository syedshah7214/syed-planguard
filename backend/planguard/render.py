"""Human-readable outputs: terminal text and GitHub-flavoured Markdown (PR comments / job summaries)."""

from __future__ import annotations

from typing import Any

ICON = {"PASS": "✅", "WARN": "⚠️", "FAIL": "⛔"}
SEV_ICON = {"critical": "🔴", "high": "🟠", "medium": "🟡", "low": "🔵"}


def _usd(v: float | None) -> str:
    return "n/a" if v is None else f"${v:,.2f}"


def markdown(r: dict[str, Any], title: str = "PlanGuard") -> str:
    c = r["cost"]
    s = r["summary"]
    lines = [
        f"## {ICON[r['decision']]} {title}: **{r['decision']}**",
        "",
        "> " + " · ".join(r["reasons"]),
        "",
        "| Plan | Create | Update | Replace | Delete |",
        "|---|---|---|---|---|",
        f"| changes | {s['create']} | {s['update']} | {s['replace']} | {s['delete']} |",
        "",
        "| Monthly cost (estimate) | Before | After | Delta | Budget |",
        "|---|---|---|---|---|",
        f"| {r['region']} on-demand, prices {r['prices_as_of']} | {_usd(c['monthly_before'])} | "
        f"{_usd(c['monthly_after'])} | {'+' if c['monthly_delta'] >= 0 else ''}{_usd(c['monthly_delta'])} | "
        f"{_usd(c['budget'])} |",
        "",
    ]
    if r["findings"]:
        lines += ["### Findings", "", "| Severity | Rule | Resource | Detail | Fix |", "|---|---|---|---|---|"]
        for f in r["findings"]:
            lines.append(
                f"| {SEV_ICON[f['severity']]} {f['severity']} | `{f['rule_id']}` {f['title']} | "
                f"`{f['address']}` | {f['detail']} | {f['remediation']} |"
            )
    else:
        lines.append("No policy findings. 🎉")
    priced = [x for x in r["resources"] if x["monthly_after"]]
    if priced:
        lines += [
            "",
            "<details><summary>Cost by resource</summary>",
            "",
            "| Resource | Action | Monthly | Basis |",
            "|---|---|---|---|",
        ]
        for x in priced:
            lines.append(f"| `{x['address']}` | {x['action']} | {_usd(x['monthly_after'])} | {x['basis']} |")
        lines += ["", "</details>"]
    lines += ["", f"<sub>Estimate excludes {c['excludes']}. Generated by SYED PlanGuard {r['tool_version']}.</sub>"]
    return "\n".join(lines)


def text(r: dict[str, Any]) -> str:
    c = r["cost"]
    out = [
        f"PlanGuard decision: {r['decision']}",
        f"  {'; '.join(r['reasons'])}",
        f"  changes: {r['summary']['create']} create, {r['summary']['update']} update, "
        f"{r['summary']['replace']} replace, {r['summary']['delete']} delete",
        f"  monthly cost: {_usd(c['monthly_before'])} -> {_usd(c['monthly_after'])} "
        f"(budget {_usd(c['budget'])}, {r['region']} list prices {r['prices_as_of']})",
    ]
    for f in r["findings"]:
        out.append(f"  [{f['severity'].upper():8}] {f['rule_id']} {f['address']}: {f['detail']}")
    return "\n".join(out)
